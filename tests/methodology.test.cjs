'use strict';
const assert=require('node:assert/strict');
const m=require('../methodology.js');
const samples=[['H335','C'],['H362','D'],['H334','E'],['H341','E'],['H315','A'],['H319','A'],['H302','B'],['H370','C'],['H351','D']];
for(const [h,b] of samples) assert.equal(m.band(h),b,h);
assert.equal(m.band('H335, H334'),'E');
for(const h of ['', 'H999', 'H225', 'H335, H999']) assert.throws(()=>m.band(h));
assert.equal(m.exposure('solido','alta','pequena'),2);
assert.equal(m.exposure('solido','baja','grande'),2);
assert.equal(m.exposure('liquido','alta','grande'),4);
assert.equal(m.exposure('liquido','baja','pequena'),1);
assert.throws(()=>m.exposure('gas','media','pequena'));
assert.equal(m.control('B',4,'solido','grande','alta'),3);
assert.equal(m.control('C',4,'solido','grande','alta'),4);
assert.equal(m.control('A',3,'liquido','mediana','alta'),2);
assert.equal(m.control('B',4,'liquido','grande','alta'),3);
assert.equal(m.control('C',3,'liquido','grande','media'),4);
assert.equal(m.control('E',1,'liquido','pequena','baja'),4);
assert.equal(m.mixture([{phrases:'H335',concentration:1}]).band,'C');
assert.equal(m.mixture([{phrases:'H334',concentration:0.01}]).band,'E');
assert.equal(m.mixture([{phrases:'H362',concentration:0.05}]).band,'D');
assert.equal(m.mixture([{phrases:'H302',concentration:9}]).band,'A');
assert.equal(m.mixture([{phrases:'H302',concentration:10}]).band,'B');
assert.throws(()=>m.mixture([{phrases:'',concentration:50}]));
assert.throws(()=>m.mixture([{phrases:'H999',concentration:100}]));
assert.throws(()=>m.mixture([{phrases:'H315',concentration:0}]));
assert.throws(()=>m.mixture([{phrases:'H315',concentration:70},{phrases:'H319',concentration:40}]));
assert.equal(m.compatibility('H225','H272').status,'ALERTA DE INCOMPATIBILIDAD');
assert.equal(m.compatibility('H315','H319').status,'NO CONCLUYENTE');
assert.throws(()=>m.compatibility('','H319'));
console.log('Control Banding: 35 pruebas de metodología OK');
